import { formatMoney, formatPdfDate, padDocumentNumber } from './format-money';
import {
  collectPdfBuffer,
  createPdfDocument,
  drawBrandHeader,
  drawFooterNotes,
  drawKeyValue,
  drawLineItemsTable,
  drawTotalsBlock,
  type PdfLineItem,
} from './pdf-document-layout';

export type QuotationPdfInput = {
  businessName: string;
  quotationNumber: number;
  revisionNumber: number;
  issueDate: Date;
  validUntil: Date | null;
  status: string;
  customerName: string;
  customerEmail: string | null;
  customerPhone: string | null;
  eventType: string | null;
  eventStartDate: Date | null;
  eventEndDate: Date | null;
  venue: string | null;
  notes: string | null;
  terms: string | null;
  subtotalAmount: number;
  discountAmount: number;
  taxAmount: number;
  totalAmount: number;
  currency: string;
  lineItems: Array<{
    description: string;
    quantity: number;
    unitPriceAmount: number;
  }>;
};

export type QuotationPdfResult = {
  buffer: Buffer;
  filename: string;
};

export async function buildQuotationPdf(
  input: QuotationPdfInput,
): Promise<QuotationPdfResult> {
  const doc = createPdfDocument();
  const bufferPromise = collectPdfBuffer(doc);
  const docNo = padDocumentNumber(input.quotationNumber);
  const filename = `Quotation-Q-${docNo}-r${input.revisionNumber}.pdf`;

  drawBrandHeader(doc, input.businessName, 'Quotation');

  doc
    .font('Helvetica-Bold')
    .fontSize(14)
    .fillColor('#1a1a1a')
    .text(`Quotation Q-${docNo} (Rev ${input.revisionNumber})`);
  doc.moveDown(0.75);

  drawKeyValue(doc, 'Issue date', formatPdfDate(input.issueDate));
  drawKeyValue(doc, 'Valid until', formatPdfDate(input.validUntil));
  drawKeyValue(doc, 'Status', input.status);
  doc.moveDown(0.4);

  doc.font('Helvetica-Bold').fontSize(11).fillColor('#1a1a1a').text('Customer');
  doc.moveDown(0.25);
  drawKeyValue(doc, 'Name', input.customerName);
  drawKeyValue(doc, 'Email', input.customerEmail ?? '—');
  drawKeyValue(doc, 'Phone', input.customerPhone ?? '—');
  doc.moveDown(0.4);

  doc
    .font('Helvetica-Bold')
    .fontSize(11)
    .fillColor('#1a1a1a')
    .text('Event details');
  doc.moveDown(0.25);
  drawKeyValue(doc, 'Type', input.eventType ?? '—');
  drawKeyValue(
    doc,
    'Dates',
    input.eventStartDate || input.eventEndDate
      ? `${formatPdfDate(input.eventStartDate)} – ${formatPdfDate(input.eventEndDate)}`
      : '—',
  );
  drawKeyValue(doc, 'Venue', input.venue ?? '—');
  doc.moveDown(0.6);

  const items: PdfLineItem[] = input.lineItems.map((line) => ({
    description: line.description,
    quantity: line.quantity,
    unitPriceAmount: line.unitPriceAmount,
    // Display product only — persisted quotation totals remain source of truth below.
    lineTotalAmount: line.quantity * line.unitPriceAmount,
  }));

  doc
    .font('Helvetica-Bold')
    .fontSize(11)
    .fillColor('#1a1a1a')
    .text('Line items');
  doc.moveDown(0.35);
  drawLineItemsTable({
    doc,
    items,
    currency: input.currency,
    formatMoney,
  });

  drawTotalsBlock(
    doc,
    {
      subtotalAmount: input.subtotalAmount,
      discountAmount: input.discountAmount,
      taxAmount: input.taxAmount,
      totalAmount: input.totalAmount,
      currency: input.currency,
    },
    formatMoney,
  );

  drawFooterNotes(doc, input.notes, input.terms);

  doc
    .moveDown(1.5)
    .font('Helvetica')
    .fontSize(8)
    .fillColor('#888888')
    .text(
      'Generated by EventOS for We Decor Events. Amounts reflect the quotation record.',
      {
        align: 'center',
      },
    );

  doc.end();
  const buffer = await bufferPromise;
  return { buffer, filename };
}
