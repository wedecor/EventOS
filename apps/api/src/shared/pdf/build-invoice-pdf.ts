import { formatMoney, formatPdfDate, padDocumentNumber } from './format-money';
import {
  collectPdfBuffer,
  createPdfDocument,
  drawBrandHeader,
  drawFooterNotes,
  drawKeyValue,
  drawLineItemsTable,
  drawTotalsBlock,
  type PdfLineItem,
} from './pdf-document-layout';

export type InvoicePdfInput = {
  businessName: string;
  invoiceNumber: number;
  invoiceDate: Date;
  status: string;
  customerName: string;
  customerEmail: string | null;
  customerPhone: string | null;
  bookingNumber: number | null;
  eventType: string | null;
  venueName: string | null;
  notes: string | null;
  subtotalAmount: number;
  taxAmount: number;
  totalAmount: number;
  currency: string;
  paidAmount: number;
  outstandingAmount: number;
  lineItems: Array<{
    description: string;
    quantity: number;
    unitPriceAmount: number;
  }>;
};

export type InvoicePdfResult = {
  buffer: Buffer;
  filename: string;
};

export async function buildInvoicePdf(
  input: InvoicePdfInput,
): Promise<InvoicePdfResult> {
  const doc = createPdfDocument();
  const bufferPromise = collectPdfBuffer(doc);
  const docNo = padDocumentNumber(input.invoiceNumber);
  const filename = `Invoice-INV-${docNo}.pdf`;

  drawBrandHeader(doc, input.businessName, 'Tax invoice / statement');

  doc
    .font('Helvetica-Bold')
    .fontSize(14)
    .fillColor('#1a1a1a')
    .text(`Invoice INV-${docNo}`);
  doc.moveDown(0.75);

  drawKeyValue(doc, 'Invoice date', formatPdfDate(input.invoiceDate));
  drawKeyValue(doc, 'Status', input.status);
  if (input.bookingNumber != null) {
    drawKeyValue(doc, 'Booking', `B-${padDocumentNumber(input.bookingNumber)}`);
  }
  doc.moveDown(0.4);

  doc.font('Helvetica-Bold').fontSize(11).fillColor('#1a1a1a').text('Bill to');
  doc.moveDown(0.25);
  drawKeyValue(doc, 'Name', input.customerName);
  drawKeyValue(doc, 'Email', input.customerEmail ?? '—');
  drawKeyValue(doc, 'Phone', input.customerPhone ?? '—');
  doc.moveDown(0.4);

  doc.font('Helvetica-Bold').fontSize(11).fillColor('#1a1a1a').text('Event');
  doc.moveDown(0.25);
  drawKeyValue(doc, 'Type', input.eventType ?? '—');
  drawKeyValue(doc, 'Venue', input.venueName ?? '—');
  doc.moveDown(0.6);

  const items: PdfLineItem[] = input.lineItems.map((line) => ({
    description: line.description,
    quantity: line.quantity,
    unitPriceAmount: line.unitPriceAmount,
    lineTotalAmount: line.quantity * line.unitPriceAmount,
  }));

  doc
    .font('Helvetica-Bold')
    .fontSize(11)
    .fillColor('#1a1a1a')
    .text('Line items');
  doc.moveDown(0.35);
  drawLineItemsTable({
    doc,
    items,
    currency: input.currency,
    formatMoney,
  });

  drawTotalsBlock(
    doc,
    {
      subtotalAmount: input.subtotalAmount,
      taxAmount: input.taxAmount,
      totalAmount: input.totalAmount,
      currency: input.currency,
    },
    formatMoney,
    [
      { label: 'Paid', amount: input.paidAmount },
      { label: 'Outstanding', amount: input.outstandingAmount },
    ],
  );

  drawFooterNotes(doc, input.notes, null);

  doc
    .moveDown(1.5)
    .font('Helvetica')
    .fontSize(8)
    .fillColor('#888888')
    .text(
      'Generated by EventOS. Totals reflect the invoice record; paid/outstanding summarise confirmed payments.',
      { align: 'center' },
    );

  doc.end();
  const buffer = await bufferPromise;
  return { buffer, filename };
}
